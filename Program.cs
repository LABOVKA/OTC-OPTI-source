    static void Run()
    {
        Log("start");
        Application.EnableVisualStyles();
        Application.SetCompatibleTextRenderingDefault(false);
        Directory.CreateDirectory(DataDir);

        if (PUBLIC_KEY.StartsWith("PASTE_"))
        {
            MessageBox.Show("В программу не вставлен публичный ключ.\nЗапустите: python keygen.py init\nзатем пересоберите программу (1-SESTAVIT.bat).", "Лицензия");
            return;
        }

        // 0) Определение Discord-аккаунта через локальный IPC (без браузера)
        DetectDiscord();

        // 1) Проверка автообновления
        CheckForUpdates();

        // 2) Сохранённая лицензия
        if (File.Exists(LicFile))
        {
            string saved = File.ReadAllText(LicFile).Trim();
            DateTime e; ulong bound; string tier;
            if (TryVerify(saved, out e, out bound, out tier) && (bound == 0 || bound.ToString() == discordId))
            {
                if (e > DateTime.UtcNow && CheckClock())
                {
                    premiumUntil = ToUnix(e);
                    licenseTier = tier;
                    Log("saved license ok, tier=" + licenseTier + ", premiumUntil=" + premiumUntil);
                }
                else if (e <= DateTime.UtcNow)
                {
                    MessageBox.Show("Срок действия лицензии истёк.\nПлатные оптимизации будут отключены.\nБесплатные функции остаются доступны.", "Лицензия");
                    try { File.Delete(LicFile); } catch { }
                    premiumUntil = 0;
                }
            }
        }

        // 3) Нет лицензии: ввести ключ или продолжить бесплатно
        while (premiumUntil == 0)
        {
            string input;
            DialogResult r = AskKey(out input);
            if (r == DialogResult.Cancel) return;
            if (r == DialogResult.Ignore) break; // Бесплатная версия

            DateTime e; ulong bound; string tier;
            if (!TryVerify(input, out e, out bound, out tier))
            {
                MessageBox.Show("Неверный ключ. Проверьте, что скопировали его полностью.", "Лицензия");
                continue;
            }
            if (bound != 0 && string.IsNullOrEmpty(discordId))
            {
                MessageBox.Show("Этот ключ привязан к Discord-аккаунту, а Discord не запущен.\nЗапустите Discord на ПК и попробуйте снова.", "Лицензия");
                continue;
            }
            if (bound != 0 && bound.ToString() != discordId)
            {
                MessageBox.Show("Этот ключ выдан для другого Discord-аккаунта (ID " + bound + ").\nВаш текущий Discord ID: " + discordId, "Лицензия");
                continue;
            }
            if (e <= DateTime.UtcNow)
            {
                MessageBox.Show("Срок действия этого ключа уже истёк.", "Лицензия");
                continue;
            }
            if (!CheckClock())
            {
                MessageBox.Show("Системное время было изменено. Исправьте время на компьютере.", "Лицензия");
                continue;
            }

            File.WriteAllText(LicFile, input.Trim());
            premiumUntil = ToUnix(e);
            licenseTier = tier;
            Log("activated new key, tier=" + licenseTier + ", premiumUntil=" + premiumUntil);
        }

        Log("license ok, tier=" + licenseTier + ", premiumUntil=" + premiumUntil + ", discord=" + (discordName ?? "-"));
        RunScript(premiumUntil, licenseTier);
    }

    // ---------- Discord IPC ----------
    static void DetectDiscord()
    {
        if (TryGetDiscordUser(out discordId, out discordName))
        {
            Log("Discord detected via IPC: " + discordName + " (" + discordId + ")");
            return;
        }

        discordId = "";
        discordName = "Гость";
        Log("Discord not running, guest mode default");
    }

    public static bool TryGetDiscordUser(out string id, out string name)
    {
        id = "";
        name = "";
        string[] clientIds = new string[] { DISCORD_CLIENT_ID, "383226320970055681" };

        for (int i = 0; i < 10; i++)
        {
            foreach (string cid in clientIds)
            {
                if (string.IsNullOrEmpty(cid) || cid.StartsWith("PASTE_")) continue;
                try
                {
                    using (NamedPipeClientStream pipe = new NamedPipeClientStream(".", "discord-ipc-" + i, PipeDirection.InOut))
                    {
                        pipe.Connect(200);
                        string json = "{\"v\":1,\"client_id\":\"" + cid + "\"}";
                        byte[] payload = Encoding.UTF8.GetBytes(json);
                        byte[] header = new byte[8];
                        BitConverter.GetBytes(0).CopyTo(header, 0); // op = 0 (handshake)
                        BitConverter.GetBytes(payload.Length).CopyTo(header, 4);

                        pipe.Write(header, 0, 8);
                        pipe.Write(payload, 0, payload.Length);
                        pipe.Flush();

                        byte[] respHeader = new byte[8];
                        int read = pipe.Read(respHeader, 0, 8);
                        if (read == 8)
                        {
                            int op = BitConverter.ToInt32(respHeader, 0);
                            int len = BitConverter.ToInt32(respHeader, 4);
                            if (op == 1 && len > 0 && len < 65536)
                            {
                                byte[] respBytes = new byte[len];
                                int total = 0;
                                while (total < len)
                                {
                                    int r = pipe.Read(respBytes, total, len - total);
                                    if (r <= 0) break;
                                    total += r;
                                }
                                string respJson = Encoding.UTF8.GetString(respBytes, 0, total);
                                Match mi = Regex.Match(respJson, "\"id\"\\s*:\\s*\"(\\d+)\"");
                                Match mg = Regex.Match(respJson, "\"global_name\"\\s*:\\s*\"([^\"]*)\"");
                                Match mn = Regex.Match(respJson, "\"username\"\\s*:\\s*\"([^\"]*)\"");

                                if (mi.Success)
                                {
                                    id = mi.Groups[1].Value;
                                    name = (mg.Success && !string.IsNullOrEmpty(mg.Groups[1].Value))
                                        ? mg.Groups[1].Value
                                        : (mn.Success ? mn.Groups[1].Value : "Discord");
                                    return true;
                                }
                            }
                        }
                    }
                }
                catch { }
            }
        }
        return false;
    }

    // ---------- Автообновления ----------
    public static void CheckForUpdates()
    {
        if (UPDATE_URL.StartsWith("PASTE_")) return;

        string tempPayload = null;
        string tempVersion = null;
        string tempVersionBackup = null;
        try
        {
            Uri manifestUri;
            if (!Uri.TryCreate(UPDATE_URL, UriKind.Absolute, out manifestUri) ||
                manifestUri.Scheme != Uri.UriSchemeHttps)
                throw new InvalidDataException("Update manifest URL must use HTTPS.");

            ServicePointManager.SecurityProtocol |= SecurityProtocolType.Tls12;
            using (WebClient wc = new UpdateWebClient())
            {
                wc.Headers["User-Agent"] = "OTC-Loader/" + LAUNCHER_VERSION;
                byte[] manifestBytes = wc.DownloadData(manifestUri);
                if (manifestBytes.Length == 0 || manifestBytes.Length > 65536)
                    throw new InvalidDataException("Update manifest size is invalid.");

                string json = new UTF8Encoding(false, true).GetString(manifestBytes);
                JavaScriptSerializer serializer = new JavaScriptSerializer();
                Dictionary<string, object> manifest =
                    serializer.Deserialize<Dictionary<string, object>>(json);
                object versionValue, scriptUrlValue, hashValue;
                if (manifest == null ||
                    !manifest.TryGetValue("version", out versionValue) ||
                    !manifest.TryGetValue("script_url", out scriptUrlValue) ||
                    !manifest.TryGetValue("sha256", out hashValue))
                    throw new InvalidDataException("Update manifest is missing required fields.");

                string remoteVer = Convert.ToString(versionValue);
                string scriptUrl = Convert.ToString(scriptUrlValue);
                string expectedHash = Convert.ToString(hashValue);
                Uri payloadUri;
                if (!Uri.TryCreate(scriptUrl, UriKind.Absolute, out payloadUri) ||
                    payloadUri.Scheme != Uri.UriSchemeHttps ||
                    !String.Equals(payloadUri.GetLeftPart(UriPartial.Authority),
                        manifestUri.GetLeftPart(UriPartial.Authority), StringComparison.OrdinalIgnoreCase))
                    throw new InvalidDataException("Payload URL must use the manifest's HTTPS origin.");
                if (!Regex.IsMatch(expectedHash, "^[0-9a-fA-F]{64}$"))
                    throw new InvalidDataException("Update manifest SHA-256 is invalid.");

                string localVerFile = Path.Combine(DataDir, "version.txt");
                string localVer = File.Exists(localVerFile)
                    ? File.ReadAllText(localVerFile).Trim()
                    : LAUNCHER_VERSION;
                Version remoteVersion, localVersion;
                if (!Version.TryParse(remoteVer, out remoteVersion) ||
                    !Version.TryParse(localVer, out localVersion))
                    throw new InvalidDataException("Update version format is invalid.");
                if (remoteVersion <= localVersion) return;

                Directory.CreateDirectory(DataDir);
                string target = Path.Combine(DataDir, "payload.ps1");
                tempPayload = Path.Combine(DataDir, "payload." + Guid.NewGuid().ToString("N") + ".tmp");
                wc.DownloadFile(payloadUri, tempPayload);
                FileInfo downloaded = new FileInfo(tempPayload);
                if (downloaded.Length == 0 || downloaded.Length > 16 * 1024 * 1024)
                    throw new InvalidDataException("Downloaded update size is invalid.");

                string actualHash;
                using (SHA256 sha256 = SHA256.Create())
                using (FileStream stream = File.OpenRead(tempPayload))
                    actualHash = BitConverter.ToString(sha256.ComputeHash(stream)).Replace("-", "");
                if (!String.Equals(actualHash, expectedHash, StringComparison.OrdinalIgnoreCase))
                    throw new InvalidDataException("Downloaded update SHA-256 does not match the manifest.");

                if (File.Exists(target))
                {
                    string backup = target + "." + Guid.NewGuid().ToString("N") + ".bak";
                    File.Replace(tempPayload, target, backup);
                    tempPayload = null;
                    File.Delete(backup);
                }
                else
                {
                    File.Move(tempPayload, target);
                    tempPayload = null;
                }

                tempVersion = localVerFile + "." + Guid.NewGuid().ToString("N") + ".tmp";
                File.WriteAllText(tempVersion, remoteVer, new UTF8Encoding(false));
                if (File.Exists(localVerFile))
                {
                    tempVersionBackup = localVerFile + "." + Guid.NewGuid().ToString("N") + ".bak";
                    File.Replace(tempVersion, localVerFile, tempVersionBackup);
                    tempVersion = null;
                    try { File.Delete(tempVersionBackup); }
                    catch (Exception ex) { Log("Could not remove previous version marker: " + ex.Message); }
                    tempVersionBackup = null;
                }
                else
                {
                    File.Move(tempVersion, localVerFile);
                    tempVersion = null;
                }
                Log("Auto-updated payload to v" + remoteVer);
            }
        }
        catch (Exception ex)
        {
            Log("Update check failed: " + ex.Message);
        }
        finally
        {
            if (tempPayload != null)
            {
                try { if (File.Exists(tempPayload)) File.Delete(tempPayload); }
                catch (Exception ex) { Log("Could not remove update temp file: " + ex.Message); }
            }
            if (tempVersion != null)
            {
                try { if (File.Exists(tempVersion)) File.Delete(tempVersion); }
                catch (Exception ex) { Log("Could not remove version temp file: " + ex.Message); }
            }
            if (tempVersionBackup != null)
            {
                try { if (File.Exists(tempVersionBackup)) File.Delete(tempVersionBackup); }
                catch (Exception ex) { Log("Could not remove previous version marker: " + ex.Message); }
            }
        }
    }

    static bool IsNewer(string remote, string local)
    {
        try
        {
            Version r = new Version(remote);
            Version l = new Version(local);
            return r > l;
        }
        catch
        {
            return false;
        }
    }

    // ---------- Запуск скрипта ----------
    public static long ToUnix(DateTime utc)
    {
        return (long)(utc - new DateTime(1970, 1, 1, 0, 0, 0, DateTimeKind.Utc)).TotalSeconds;
    }

    public static void RunScript(long premUntil, string tier)
    {
        string text = null;
        string updatedScript = Path.Combine(DataDir, "payload.ps1");
        if (File.Exists(updatedScript))
        {
            try
            {
                text = File.ReadAllText(updatedScript, Encoding.UTF8);
                Log("Using updated payload from disk: " + updatedScript);
            }
            catch { }
        }

        if (string.IsNullOrEmpty(text))
        {
            using (Stream s = Assembly.GetExecutingAssembly().GetManifestResourceStream("payload.ps1"))
            using (StreamReader rd = new StreamReader(s, new UTF8Encoding(false)))
                text = rd.ReadToEnd();
        }

        string tmp = Path.Combine(Path.GetTempPath(), "OTC-OPTI-" + Guid.NewGuid().ToString("N") + ".ps1");
        File.WriteAllText(tmp, text, new UTF8Encoding(true)); // UTF-8 с BOM

        try
        {
            string ps = Path.Combine(Environment.SystemDirectory, @"WindowsPowerShell\v1.0\powershell.exe");
            if (!File.Exists(ps)) ps = "powershell.exe";

            ProcessStartInfo psi = new ProcessStartInfo(ps,
                "-NoLogo -NoProfile -STA -ExecutionPolicy Bypass -File \"" + tmp + "\"");
            psi.UseShellExecute = false;
            psi.CreateNoWindow = true;
            psi.EnvironmentVariables["OTC_PREMIUM_UNTIL"] = premUntil.ToString();
            psi.EnvironmentVariables["OTC_LICENSE_TIER"] = tier ?? "FREE";
            psi.EnvironmentVariables["OTC_PUBKEY"] = PUBLIC_KEY + "," + String.Join(",", LEGACY_PUBLIC_KEYS);
            psi.EnvironmentVariables["OTC_DISCORD_ID"] = discordId ?? "";
            psi.EnvironmentVariables["OTC_DISCORD_NAME"] = discordName ?? "";
            psi.EnvironmentVariables["OTC_DISCORD_URL"] = DISCORD_URL;
            psi.EnvironmentVariables["OTC_WEB_URL"] = WEB_URL;

            psi.RedirectStandardOutput = true;
            psi.RedirectStandardError = true;
            StringBuilder outp = new StringBuilder();
            DateTime t0 = DateTime.UtcNow;
            int code;
            Log("starting PowerShell: " + tmp);
            using (Process p = Process.Start(psi))
            {
                p.OutputDataReceived += delegate(object sender, DataReceivedEventArgs ev) { if (ev.Data != null) lock (outp) outp.AppendLine(ev.Data); };
                p.ErrorDataReceived += delegate(object sender, DataReceivedEventArgs ev) { if (ev.Data != null) lock (outp) outp.AppendLine(ev.Data); };
                p.BeginOutputReadLine();
                p.BeginErrorReadLine();
                p.WaitForExit();
                code = p.ExitCode;
            }
            double secs = (DateTime.UtcNow - t0).TotalSeconds;
            string psText;
            lock (outp) psText = outp.ToString().Trim();
            Log("PowerShell exit code " + code + " after " + secs.ToString("0.0") + " s");
            if (psText.Length > 0) Log("PowerShell output:\r\n" + psText);
            if (code != 0 || (secs < 20 && psText.Length > 0))
            {
                string shown = psText.Length > 1500 ? psText.Substring(0, 1500) + "..." : psText;
                MessageBox.Show("OTC OPTI не запустился (код " + code + ").\n\n" + shown + "\n\nЛог: " + LogFile, "OTC OPTI");
            }
        }
        catch (Exception ex)
        {
            Log("RunScript error: " + ex.ToString());
            MessageBox.Show("Не удалось запустить OTC OPTI:\n" + ex.Message + "\n\nЛог: " + LogFile, "OTC OPTI");
        }
        finally
        {
            try { File.Delete(tmp); } catch { }
        }
    }

    // ---------- Проверка ключей ----------
    public static bool TryVerify(string key, out DateTime expiryUtc, out ulong boundId, out string tier)
    {
        expiryUtc = DateTime.MinValue;
        boundId = 0;
        tier = "FREE";
        try
        {
            key = key.Trim().Replace(" ", "").Replace("\r", "").Replace("\n", "");
            byte[] raw = FromB64Url(key);
            if (raw.Length != 80) return false;

            byte[] payload = new byte[16];
            byte[] sig = new byte[64];
            Array.Copy(raw, 0, payload, 0, 16);
            Array.Copy(raw, 16, sig, 0, 64);

            bool verified = false;
            List<string> publicKeys = new List<string>();
            if (!PUBLIC_KEY.StartsWith("PASTE_")) publicKeys.Add(PUBLIC_KEY);
            publicKeys.AddRange(LEGACY_PUBLIC_KEYS);
            foreach (string encodedKey in publicKeys)
            {
                byte[] pub = Convert.FromBase64String(encodedKey);
                if (pub.Length != 64) continue;
                byte[] x = new byte[32], y = new byte[32];
                Array.Copy(pub, 0, x, 0, 32);
                Array.Copy(pub, 32, y, 0, 32);

                ECParameters p = new ECParameters();
                p.Curve = ECCurve.NamedCurves.nistP256;
                p.Q.X = x;
                p.Q.Y = y;

                using (ECDsa ecdsa = ECDsa.Create(p))
                {
                    if (ecdsa.VerifyData(payload, sig, HashAlgorithmName.SHA256))
                    {
                        verified = true;
                        break;
                    }
                }
            }
            if (!verified) return false;

            uint secs = ((uint)payload[0] << 24) | ((uint)payload[1] << 16) | ((uint)payload[2] << 8) | payload[3];
            expiryUtc = secs == UInt32.MaxValue
                ? DateTime.MaxValue
                : new DateTime(1970, 1, 1, 0, 0, 0, DateTimeKind.Utc).AddSeconds(secs);
            string marker = Encoding.ASCII.GetString(payload, 4, 4);
            tier = marker == "PLUS" ? "PLUS" : "ULTRA"; // Legacy signed keys used random bytes here; keep their full access.
            ulong b = 0;
            for (int i = 8; i < 16; i++) b = (b << 8) | payload[i];
            boundId = b;
            return true;
        }
        catch { return false; }
    }

    static byte[] FromB64Url(string s)
    {
        s = s.Replace('-', '+').Replace('_', '/');
        switch (s.Length % 4) { case 2: s += "=="; break; case 3: s += "="; break; }
        return Convert.FromBase64String(s);
    }

    public static bool CheckClock()
    {
        try
        {
            long now = DateTime.UtcNow.Ticks;
            long last = 0;
            if (File.Exists(TimeFile)) long.TryParse(File.ReadAllText(TimeFile), out last);
            if (now < last - TimeSpan.FromMinutes(10).Ticks) return false;
            File.WriteAllText(TimeFile, Math.Max(now, last).ToString());
            return true;
        }
        catch { return true; }
    }

